"""Fit a stage-assignment heuristic on six DiffSched replicas and evaluate twelve other replicas."""

import argparse
from collections import Counter
from contextlib import redirect_stdout
from graphlib import TopologicalSorter
from io import StringIO
import json
import math
import os
from pathlib import Path
import re
import statistics
import subprocess
import time

import networkx as nx

from flow_pilot import model_call
from run_round import HERE, SOURCES, digest, sandbox, write_json

SOURCE = SOURCES / "diffsched_icml24"
DEPTH = 10
RATIO = 10
BASE = "def improve(weights, edges, stages, depth, ratio):\n    return stages\n"
PROMPT = """Implement a reusable function improve(weights, edges, stages, depth, ratio) for stage placement.
Return Python code defining the function (up to 3700 characters) and a short strategy. Python standard
library only. weights: list of nonnegative integer node weights. edges: list of triples (u,v,w), w is
indicator 0 or 1. stages: initial feasible list of integers in [0,depth-1], generated by assigning
balanced consecutive chunks of a topological order. Return feasible list, same length, with each
edge satisfying s[u] <= s[v] (equal stages are legal). Minimize ratio times maximum per-stage
sum of node weights plus sum(w*(s[v]-s[u]) for all edges). Equal peak can hide progress: consider
lexicographic plateau moves reducing imbalance and communication, or restarting from different topo orders.
At most ~10000 nodes and ~50000 edges, depth=10, ratio=10. 10s wall limit on 1 CPU per graph;
avoid quadratic loops. Candidate may return original baseline if no improvement. Never use instance
identifiers or read files. Generalize across replicas; keep the best legal solution seen.
"""


def read_graph(path):
    # NetworkX's default labels correspond exactly to the author's parse_graph_w_attr.py.
    g = nx.relabel_nodes(nx.read_gml(path), lambda x: int(x))
    if set(g.nodes) != set(range(len(g))):
        raise ValueError("expected contiguous integer node labels")
    weights = [int(g.nodes[i]["parameter"]) for i in range(len(g))]
    edges = [(i, j, min(1, int(g.edges[i, j]["parameter"]))) for i, j in g.edges]
    if not weights or min(weights) < 0 or any(w < 0 for _, _, w in edges):
        raise ValueError("unexpected weight domain")
    parents = {i: [] for i in range(len(g))}
    for i, j, _ in edges:
        parents[j].append(i)
    order = list(TopologicalSorter(parents).static_order())
    total = sum(weights)
    cumulative = 0
    stages = [0] * len(weights)
    for i in order:
        stages[i] = min(DEPTH - 1, ((2*cumulative + weights[i]) * DEPTH) // (2*max(1, total)))
        cumulative += weights[i]
    return weights, edges, stages


def cost(weights, edges, stages):
    if not isinstance(stages, list) or len(stages) != len(weights):
        raise ValueError("wrong stage list length")
    if any(type(s) is not int or not 0 <= s < DEPTH for s in stages):
        raise ValueError("illegal stage index")
    loads = [0] * DEPTH
    for s, w in zip(stages, weights):
        loads[s] += w
    communication = 0
    for u, v, w in edges:
        if stages[u] > stages[v]:
            raise ValueError("backwards dependency")
        communication += (stages[v] - stages[u]) * w
    return {"objective": RATIO*max(loads) + communication, "peak": max(loads), "communication": communication}


def official_check():
    # Execute only the upstream code generator for legal_check, avoiding construction/training
    # of the CUDA neural network. Its output is saved for inspection and hashed by the caller.
    source = (SOURCE / "parse_graph_w_attr.py").read_text()
    start = source.index('print("def legal_check(')
    end = source.index('print("def multiconditional_', start)
    generated = StringIO()
    with redirect_stdout(generated):
        exec(compile(source[start:end], "upstream-legal-check-generator", "exec"), {"depth": DEPTH})
    namespace = {"nx": nx}
    exec(compile(generated.getvalue(), "upstream-legal-check", "exec"), namespace)
    return namespace["legal_check"], generated.getvalue()


def evaluate(path, dataset, policy, folder, cpu, checker, input_path):
    weights, edges, stages = dataset
    folder.mkdir(parents=True)
    output = folder / "output"
    output.mkdir()
    command = ["taskset", "-c", str(cpu)] + sandbox() + [
        "--ro-bind", str(policy), "/rule.py", "--ro-bind", str(input_path), "/graph.json",
        "--bind", str(output), "/output", "/usr/bin/python3", "-I", "-B", "-c",
        "import json,resource,runpy;"
        "resource.setrlimit(resource.RLIMIT_AS,(512<<20,512<<20));"
        "resource.setrlimit(resource.RLIMIT_FSIZE,(1<<20,1<<20));"
        "resource.setrlimit(resource.RLIMIT_CORE,(0,0));"
        "w,e,s,d,r=json.load(open('/graph.json'));"
        "json.dump(runpy.run_path('/rule.py')['improve'](w,e,s,d,r),open('/output/stages.json','w'))",
    ]
    begin = time.perf_counter()
    try:
        with (folder / "process.log").open("wb") as log:
            proc = subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, timeout=10)
        elapsed = time.perf_counter() - begin
        if proc.returncode:
            raise ValueError(f"process exit {proc.returncode}")
        file = output / "stages.json"
        if file.is_symlink() or not file.is_file() or file.stat().st_size > 1 << 20:
            raise ValueError("invalid solution file")
        guess = json.loads(file.read_text())
        score = cost(weights, edges, guess)
    except (ValueError, OSError, subprocess.TimeoutExpired) as error:
        return {"status": "failed", "error": str(error), "seconds": time.perf_counter()-begin}
    if checker(guess, str(path)) != score["communication"]:
        raise ValueError(f"official legality/communication check mismatch on {path.stem}")
    return {"status": "valid", "seconds": elapsed, **score, "schedule_sha256": digest(file)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--model", default="gpt-6.1-sol")
    parser.add_argument("--effort", default="medium")
    parser.add_argument("--replay", type=Path, help="Re-evaluate frozen code from a compact result without a model call.")
    args = parser.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True)
    cpu = min(os.sched_getaffinity(0))
    subprocess.run(sandbox() + ["/usr/bin/true"], check=True)
    checker, generated = official_check()
    verifier = out / "upstream_legal_check.py"
    verifier.write_text(generated)
    graphs = sorted((SOURCE / "graphgml").glob("*.gml"))
    dev = [g for g in graphs if g.stem.endswith("_1")]
    test = [g for g in graphs if g not in dev]
    if (len(dev), len(test)) != (6, 12):
        raise ValueError("unexpected pinned split")
    data, examples, native = {}, {}, {}
    source_paths = {g.stem: out / (g.stem + ".json") for g in graphs}
    for g in graphs:
        weights, edges, stages = data[g.stem] = read_graph(g)
        write_json(source_paths[g.stem], [weights, edges, stages, DEPTH, RATIO])
        native[g.stem] = cost(weights, edges, stages)
        if checker(stages, str(g)) != native[g.stem]["communication"]:
            raise ValueError("initial schedule failed upstream verifier")
        examples[g.stem] = {"nodes": len(weights), "edges": len(edges), "input_sha256": digest(g),
                            "lower_bound": RATIO * max(max(weights), math.ceil(sum(weights) / DEPTH)),
                            "initial": native[g.stem]}
    frozen = json.loads(args.replay.read_text()) if args.replay else None
    config = {"cpu": cpu, "model": args.model, "reasoning_effort": args.effort, "depth": DEPTH, "ratio": RATIO,
              "wall_seconds_per_graph": 10, "networkx": nx.__version__, "runner_sha256": digest(Path(__file__)),
              "upstream_generator_sha256": digest(SOURCE / "parse_graph_w_attr.py"),
              "upstream_check_sha256": digest(verifier), "dev": [p.stem for p in dev], "test": [p.stem for p in test],
              "selection": "maximize dev valid count; minimize dev geometric mean ratio; earliest candidate including seed"}
    write_json(out / "protocol.json", config)
    prefix = PROMPT + "\nDevelopment seed scores:\n" + json.dumps({p.stem: examples[p.stem] for p in dev})
    records = []
    for index in range(3):
        folder = out / f"candidate_{index}"
        folder.mkdir()
        if index == 0:
            code, strategy, receipt = BASE, "Weighted balanced topological chunks", {}
        elif frozen:
            item = frozen["candidates"][index]
            code, strategy, receipt = item["code"], item["strategy"], {"status": "replay"}
        else:
            context = "" if index == 1 else "\nPrevious candidate and its development results:\n" + json.dumps(
                {k: records[-1][k] for k in ("code", "strategy", "dev")})
            reply, receipt = model_call(prefix + context, ["code", "strategy"], folder / "model", args.model, args.effort)
            code, strategy = (reply["code"], reply["strategy"]) if reply else ("", "")
        policy = folder / "policy.py"
        policy.write_text(code + "\n")
        scores = {p.stem: evaluate(p, data[p.stem], policy, folder / p.stem, cpu, checker, source_paths[p.stem])
                  for p in dev} if code else {}
        records.append({"index": index, "code": code, "strategy": strategy, "sha256": digest(policy),
                        "receipt": receipt, "dev": scores})
    def selection(item):
        ratios = [v["objective"] / native[k]["objective"] for k, v in item["dev"].items() if v["status"] == "valid"]
        return -len(ratios), statistics.geometric_mean(ratios) if ratios else math.inf, item["index"]

    winner = min(records, key=selection)
    write_json(out / "selection.json", {"index": winner["index"], "sha256": winner["sha256"]})
    policy = out / f"candidate_{winner['index']}" / "policy.py"
    holdout = {p.stem: evaluate(p, data[p.stem], policy, out / "holdout" / p.stem, cpu, checker, source_paths[p.stem])
               for p in test}
    write_json(out / "results.json", {"protocol": config, "graphs": examples, "candidates": records,
                                      "selected": winner["index"], "holdout": holdout})
    print("selected", winner["index"], "holdout statuses", Counter(v["status"] for v in holdout.values()))


if __name__ == "__main__":
    main()
